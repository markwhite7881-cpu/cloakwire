import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const cli = fileURLToPath(new URL('./release-version.mjs', import.meta.url));
const androidPath = 'src-tauri/gen/android/app/tauri.properties';
const sourcePaths = ['src-tauri/tauri.conf.json', 'package.json', 'package-lock.json', 'src-tauri/Cargo.toml', 'src-tauri/Cargo.lock'];

function put(root, path, content) {
  const target = join(root, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}

function fixture(t, version = '1.4.8', android = true) {
  const root = mkdtempSync(join(tmpdir(), 'cloakwire-version-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  put(root, sourcePaths[0], JSON.stringify({ version, productName: 'Cloakwire' }, null, 2) + '\n');
  put(root, sourcePaths[1], JSON.stringify({ name: 'cloakwire', version, dependencies: { other: '1.4.8' } }, null, 2) + '\n');
  put(root, sourcePaths[2], JSON.stringify({ name: 'cloakwire', version, lockfileVersion: 3, packages: { '': { name: 'cloakwire', version }, 'node_modules/other': { version: '1.4.8' } } }, null, 2) + '\n');
  put(root, sourcePaths[3], `[package]\nname = "cloakwire"\nversion = "${version}" # app\n\n[dependencies]\nother = { version = "1.4.8" }\n`);
  put(root, sourcePaths[4], `# Cargo lock\nversion = 3\n\n[[package]]\nname = "other"\nversion = "1.4.8"\n\n[[package]]\nname = "cloakwire"\nversion = "${version}"\ndependencies = [\n "other",\n]\n\n[[package]]\nname = "trailing"\nversion = "1.4.8"\n`);
  if (android) put(root, androidPath, '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\ntauri.android.versionName=1.4.8\ntauri.android.versionCode=1004008\n');
  return root;
}

function run(root, ...args) {
  return spawnSync(process.execPath, [cli, ...args, '--project-root', root], { encoding: 'utf8' });
}

function ok(result) {
  assert.equal(result.status, 0, result.stderr || result.error?.message);
  assert.equal(result.stderr, '');
  return result.stdout.trim();
}

function fail(result, pattern) {
  assert.notEqual(result.status, 0, result.stdout);
  assert.doesNotMatch(result.stderr, /MODULE_NOT_FOUND|ERR_MODULE_NOT_FOUND/);
  assert.match(result.stderr, pattern);
  assert.equal(result.stdout, '');
}

function snapshot(root) {
  return Object.fromEntries([...sourcePaths, androidPath].map(path => {
    try { return [path, readFileSync(join(root, path), 'utf8')]; }
    catch (error) { if (error.code === 'ENOENT') return [path, null]; throw error; }
  }));
}

function changeJson(root, path, mutate) {
  const value = JSON.parse(readFileSync(join(root, path), 'utf8'));
  mutate(value);
  put(root, path, JSON.stringify(value, null, 2) + '\n');
}

test('check returns the canonical release and Android code without writing files', t => {
  const root = fixture(t);
  const before = snapshot(root);
  assert.deepEqual(JSON.parse(ok(run(root, 'check'))), { version: '1.4.8', androidVersionCode: 1004008 });
  assert.equal(ok(run(root, 'get')), '1.4.8');
  assert.deepEqual(snapshot(root), before);
});

test('set updates every app version and preserves unrelated dependency versions', t => {
  const root = fixture(t);
  assert.deepEqual(JSON.parse(ok(run(root, 'set', '1.4.9'))), { version: '1.4.9', androidVersionCode: 1004009 });
  assert.deepEqual(JSON.parse(ok(run(root, 'check', '--version', '1.4.9'))), { version: '1.4.9', androidVersionCode: 1004009 });
  const files = snapshot(root);
  assert.equal(JSON.parse(files[sourcePaths[0]]).version, '1.4.9');
  assert.equal(JSON.parse(files[sourcePaths[1]]).version, '1.4.9');
  const lock = JSON.parse(files[sourcePaths[2]]);
  assert.equal(lock.version, '1.4.9');
  assert.equal(lock.packages[''].version, '1.4.9');
  assert.equal(lock.packages['node_modules/other'].version, '1.4.8');
  assert.match(files[sourcePaths[3]], /version = "1\.4\.9" # app/);
  assert.match(files[sourcePaths[3]], /other = \{ version = "1\.4\.8" \}/);
  assert.match(files[sourcePaths[4]], /name = "cloakwire"\nversion = "1\.4\.9"/);
  assert.match(files[sourcePaths[4]], /name = "other"\nversion = "1\.4\.8"/);
  assert.match(files[sourcePaths[4]], /name = "trailing"\nversion = "1\.4\.8"/);
  assert.match(files[androidPath], /versionName=1\.4\.9\ntauri\.android\.versionCode=1004009\n$/);
});

test('multi-digit patch versions retain their exact name and numeric Android code', t => {
  const root = fixture(t);
  assert.deepEqual(JSON.parse(ok(run(root, 'set', '1.4.10'))), { version: '1.4.10', androidVersionCode: 1004010 });
  assert.equal(ok(run(root, 'get')), '1.4.10');
});

const mismatches = [
  ['package.json', value => { value.version = '1.4.7'; }],
  ['package-lock.json', value => { value.version = '1.4.7'; }],
  ['package-lock.json', value => { value.packages[''].version = '1.4.7'; }],
];
for (const [path, mutate] of mismatches) {
  test(`check rejects a mismatched ${path} app version`, t => {
    const root = fixture(t);
    changeJson(root, path, mutate);
    fail(run(root, 'check'), /version.*mismatch|must match/i);
  });
}
for (const path of ['src-tauri/Cargo.toml', 'src-tauri/Cargo.lock']) {
  test(`check rejects a mismatched ${path} app version`, t => {
    const root = fixture(t);
    put(root, path, readFileSync(join(root, path), 'utf8').replace(/(name = "cloakwire"\nversion = ")1\.4\.8/, '$11.4.7'));
    fail(run(root, 'check'), /version.*mismatch|must match/i);
  });
}

test('expected version mismatch fails without a write', t => {
  const root = fixture(t);
  const before = snapshot(root);
  fail(run(root, 'check', '--version', '1.4.9'), /expected.*1\.4\.9|1\.4\.9.*expected/i);
  assert.deepEqual(snapshot(root), before);
});

test('check accepts absent generated Android metadata and sync-android generates it without source edits', t => {
  const root = fixture(t, '1.4.8', false);
  const before = snapshot(root);
  assert.equal(JSON.parse(ok(run(root, 'check'))).version, '1.4.8');
  assert.deepEqual(snapshot(root), before);
  assert.deepEqual(JSON.parse(ok(run(root, 'sync-android'))), { version: '1.4.8', androidVersionCode: 1004008 });
  const after = snapshot(root);
  for (const path of sourcePaths) assert.equal(after[path], before[path], path);
  assert.match(after[androidPath], /versionCode=1004008/);
});

test('check rejects stale Android metadata and sync-android repairs only generated metadata', t => {
  const root = fixture(t);
  put(root, androidPath, 'tauri.android.versionName=1.4.7\ntauri.android.versionCode=1004007\n');
  const before = snapshot(root);
  fail(run(root, 'check'), /Android.*metadata|Android.*version/i);
  ok(run(root, 'sync-android', '--version', '1.4.8'));
  ok(run(root, 'check'));
  const after = snapshot(root);
  for (const path of sourcePaths) assert.equal(after[path], before[path], path);
});

test('sync-android refuses inconsistent source versions', t => {
  const root = fixture(t);
  changeJson(root, 'package.json', value => { value.version = '1.4.7'; });
  const before = snapshot(root);
  fail(run(root, 'sync-android'), /version.*mismatch|must match/i);
  assert.deepEqual(snapshot(root), before);
});

for (const version of ['1.4', '01.4.9', '1.4.9-beta.1', '1.4.9+build', '-1.4.9', '1.4.9\n', '2148.0.0', '99999999999999999999999999.0.0', '2147.483.648', '1.1000.0', '1.4.1000', '0.0.0']) {
  test(`set rejects invalid or unrepresentable version ${JSON.stringify(version)} without partial updates`, t => {
    const root = fixture(t);
    const before = snapshot(root);
    fail(run(root, 'set', version), /version|numeric/i);
    assert.deepEqual(snapshot(root), before);
  });
}

test('Android versionCode accepts the exact signed 32-bit upper bound', t => {
  const root = fixture(t);
  assert.deepEqual(JSON.parse(ok(run(root, 'set', '2147.483.647'))), { version: '2147.483.647', androidVersionCode: 2147483647 });
  ok(run(root, 'check'));
});

const malformedFiles = [
  ['package-lock.json', '{invalid json'],
  ['package-lock.json', '{"version":"1.4.8","packages":{}}'],
  ['src-tauri/Cargo.toml', '[package]\nname = "cloakwire"\n'],
  ['src-tauri/Cargo.toml', '[package]\nname = "cloakwire"\nversion = "1.4.8"\nversion = "1.4.8"\n'],
  ['src-tauri/Cargo.lock', '[[package]]\nname = "other"\nversion = "1.4.8"\n'],
  ['src-tauri/Cargo.lock', '[[package]]\nname = "cloakwire"\nversion = "1.4.8"\n\n[[package]]\nname = "cloakwire"\nversion = "1.4.8"\n'],
  ['src-tauri/tauri.conf.json', '{"version":"1.04.8"}'],
];
for (const [path, contents] of malformedFiles) {
  test(`set validates malformed ${path} before updating any source file`, t => {
    const root = fixture(t);
    put(root, path, contents);
    const before = snapshot(root);
    fail(run(root, 'set', '1.4.9'), /invalid|missing|exactly|version|package/i);
    assert.deepEqual(snapshot(root), before);
  });
}

test('set can explicitly repair stale but valid source versions', t => {
  const root = fixture(t);
  changeJson(root, 'package.json', value => { value.version = '1.4.7'; });
  ok(run(root, 'set', '1.4.9'));
  ok(run(root, 'check', '--version', '1.4.9'));
});

test('setting the same version is byte-for-byte idempotent with CRLF source files', t => {
  const root = fixture(t);
  for (const path of sourcePaths) put(root, path, readFileSync(join(root, path), 'utf8').replaceAll('\n', '\r\n'));
  const before = snapshot(root);
  ok(run(root, 'set', '1.4.8'));
  assert.deepEqual(snapshot(root), before);
});

for (const args of [[], ['unknown'], ['set'], ['check', '--unknown'], ['check', '--project-root'], ['check', '--version'], ['check', '1.4.9'], ['get', '--version', '1.4.8'], ['set', '1.4.9', '--version', '1.4.9']]) {
  test(`CLI rejects invalid arguments ${JSON.stringify(args)}`, t => {
    const root = fixture(t);
    const result = spawnSync(process.execPath, [cli, '--project-root', root, ...args], { encoding: 'utf8' });
    fail(result, /usage|unknown|argument|requires|only|duplicate/i);
  });
}
